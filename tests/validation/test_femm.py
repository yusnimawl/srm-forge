"""FEMM 4.2 cross-tool comparison (spec §2.3, §8.2 suite 4, §8.3): srmcore `full` against committed FEMM
fixtures generated by tools/femm_fixtures.py (docs/m5c-femm-results.md)."""
import json
import math
from pathlib import Path

import pytest

import femm_machines as fm
from srmcore.fields.solution import SolveStatus
from srmcore.maps.point import solve_point
from srmcore.mesh import build_machine_mesh

FIXTURES = Path(__file__).parent / "fixtures"
PSI_TOLERANCE = 0.02
TORQUE_FLOOR = 0.01            # fraction of the peak FEMM torque at the same current
FEMM_METHODS_AGREE = 0.01      # air-gap element vs stress tensor, fraction of peak

pytestmark = pytest.mark.slow


def _solver():
    try:
        from srmcore.solvers.ngsolve_adapter import NgsolveAdapter
        return NgsolveAdapter()
    except ImportError:
        from srmcore.solvers.skfem_reference import SkfemReference
        return SkfemReference()


def _peaks(points):
    peak = {}
    for q in points:
        peak[q["current"]] = max(peak.get(q["current"], 0.0), abs(q["torque_age"]))
    return peak


@pytest.fixture(scope="module", params=list(fm.MACHINES))
def compared(request):
    name = request.param
    fixture = json.loads((FIXTURES / f"femm_{name}.json").read_text())
    d = fm.design(name)
    prov = fixture["provenance"]
    stale = [k for k, now in (("design_sha256", fm.design_sha256(d)), ("bh_sha256", fm.bh_sha256(d)))
             if prov[k] != now]
    solver = _solver()
    rows = []
    if not stale:
        with fm.waivers(name):
            static = build_machine_mesh(d)
            for q in fixture["points"]:
                r = solve_point(static, d, q["angle"], {"A": q["current"]}, solver)
                rows.append((q, r))
    return name, stale, fixture, rows


def test_fixture_is_fresh(compared):
    name, stale, _, _ = compared
    assert not stale, (f"FEMM fixture for {name} is stale ({', '.join(stale)} changed); regenerate with "
                       f"tools/femm_fixtures.py {name}")


def test_angles_and_status(compared):
    _, stale, _, rows = compared
    if stale:
        pytest.skip("stale fixture")
    for q, r in rows:
        assert math.isclose(r.angle, q["angle"] % (2 * math.pi), abs_tol=1e-12)
        assert r.status in (SolveStatus.OK, SolveStatus.OK_WITH_FALLBACK)


def test_flux_linkage_within_2_percent(compared):
    _, stale, _, rows = compared
    if stale:
        pytest.skip("stale fixture")
    bad = [f"{math.degrees(q['angle']):.2f} deg {q['current']} A: {r.psi[0] / q['psi'] - 1:+.3%}"
           for q, r in rows if abs(r.psi[0] - q["psi"]) > PSI_TOLERANCE * abs(q["psi"])]
    assert not bad, bad


def test_torque_within_tiered_tolerance(compared):
    _, stale, fixture, rows = compared
    if stale:
        pytest.skip("stale fixture")
    peak = _peaks(fixture["points"])
    bad = []
    for q, r in rows:
        limit = max(q["tolerance"] * abs(q["torque_age"]), TORQUE_FLOOR * peak[q["current"]])
        err = r.torque_arkkio - q["torque_age"]
        if abs(err) > limit:
            bad.append(f"{math.degrees(q['angle']):.2f} deg {q['current']} A: dT {err:+.4g} N m, limit {limit:.4g}")
    assert not bad, bad


def test_femm_torque_methods_agree(compared):
    _, _, fixture, _ = compared
    peak = _peaks(fixture["points"])
    bad = [f"{math.degrees(q['angle']):.2f} deg {q['current']} A"
           for q in fixture["points"]
           if abs(q["torque_age"] - q["torque_wst"]) > FEMM_METHODS_AGREE * peak[q["current"]]]
    assert not bad, bad
